  let current = 'en';

  function language(id) {
    return ui[id] ? id : 'en';
  }

  function value(key, id = current) {
    const parts = key.split('.');
    let result = ui[language(id)];
    for (const part of parts) result = result && result[part];
    if (result === undefined && id !== 'en') return value(key, 'en');
    return result === undefined ? key : result;
  }

  // true when the language's own catalogue has the line; value() and t() fall back to English
  function has(key, id = current) {
    let result = ui[language(id)];
    for (const part of key.split('.')) result = result && result[part];
    return result !== undefined;
  }

  function interpolate(template, vars = {}) {
    return String(template).replace(/\{([a-zA-Z0-9_]+)\}/g, (match, name) => vars[name] === undefined ? match : vars[name]);
  }

  function t(key, vars) {
    return interpolate(value(key), vars);
  }

  // "{count} day" or "{count} days": a table with one and other, picked by the count. Every
  // count shown is 1 or more, so one and other cover each language here.
  function plural(key, count, vars) {
    return t(`${key}.${Number(count) === 1 ? 'one' : 'other'}`, Object.assign({ count }, vars));
  }

  function setLanguage(id) {
    current = language(id);
    return current;
  }

  // a companion's own moving/combat lines in the current language, or null
  function caption(species, state) {
    const pair = ui[current] && ui[current].captions && ui[current].captions[species] && ui[current].captions[species][state];
    return Array.isArray(pair) ? pair : null;
  }

