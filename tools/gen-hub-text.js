#!/usr/bin/env node
// Writes the text that lives outside the pages from view/i18n.js, in every language:
//   src/HubText.h         the plugin's own text (DovahHub's Settings labels, the leftover-DLL message)
//   view/dovahmenu.json   DovahMenu's entry; its description per language (menuDescription)
//
//   node tools/gen-hub-text.js           rewrite both
//   node tools/gen-hub-text.js --check   exit 1 if either is out of date
//
// Non-ASCII bytes are written as octal escapes, so the header compiles the same whatever code page
// the compiler reads the source in. tests/translation-coverage.test.js runs the check.
'use strict';
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const HEADER = path.join(ROOT, 'src', 'HubText.h');
const FIELDS = ['raisePet', 'raisePetHint', 'hubShowClock', 'clockStyle', 'plate', 'ribbon', 'hubCardSize', 'hubCardShape',
  'square', 'wide', 'hubHideCard', 'hubHideCardNote', 'language', 'machineTranslationNote', 'leftoverDll',
  'reactToMods', 'reactToModsNote', 'reactionCooldown', 'careMoments', 'careMomentsNote', 'chronicleLines', 'chronicleLinesNote'];

function cString(text) {
  let out = '"';
  let afterEscape = false;
  for (const byte of Buffer.from(String(text), 'utf8')) {
    const octal = byte < 0x20 || byte >= 0x7f;
    // a digit right after an octal escape reads as one to the compiler's eye (C4125): close the literal
    if (afterEscape && byte >= 0x30 && byte <= 0x39) out += '" "';
    if (byte === 0x22) out += '\\"';
    else if (byte === 0x5c) out += '\\\\';
    else if (byte === 0x0a) out += '\\n';
    else if (octal) out += '\\' + byte.toString(8).padStart(3, '0');
    else out += String.fromCharCode(byte);
    afterEscape = octal && byte !== 0x0a;
  }
  return out + '"';
}

function render() {
  delete require.cache[require.resolve(path.join(ROOT, 'view', 'i18n.js'))];
  const i18n = require(path.join(ROOT, 'view', 'i18n.js'));
  const rows = i18n.languages.map(id => {
    i18n.setLanguage(id);
    const values = [id, i18n.languageNames[id], ...FIELDS.map(field => i18n.t(field))];
    return `        { ${values.map(cString).join(',\n          ')} }`;
  });
  i18n.setLanguage('en');
  return [
    '// Generated by tools/gen-hub-text.js from view/i18n.js. Change the catalogue, then run',
    '// `node tools/gen-hub-text.js`; tests/translation-coverage.test.js fails while this is out of date.',
    '#pragma once',
    '',
    '#include <string_view>',
    '',
    'namespace HubText',
    '{',
    '    struct Text',
    '    {',
    '        const char* code;',
    '        const char* languageName;',
    ...FIELDS.map(field => `        const char* ${field};`),
    '    };',
    '',
    '    inline constexpr Text kTexts[] = {',
    rows.join(',\n'),
    '    };',
    '',
    '    // the text for a language code, English when the code is unknown',
    '    inline const Text& For(std::string_view code)',
    '    {',
    '        for (const auto& text : kTexts) {',
    '            if (code == text.code) {',
    '                return text;',
    '            }',
    '        }',
    '        return kTexts[0];',
    '    }',
    '}',
    ''
  ].join('\n');
}

const MENU = path.join(ROOT, 'view', 'dovahmenu.json');

// dovahmenu.json with its description in every language; name, version, hotkey and hidden are kept
function renderMenu() {
  const i18n = require(path.join(ROOT, 'view', 'i18n.js'));
  const current = JSON.parse(fs.readFileSync(MENU, 'utf8'));
  const description = {};
  for (const id of i18n.languages) {
    i18n.setLanguage(id);
    description[id] = i18n.t('menuDescription');
  }
  i18n.setLanguage('en');
  return JSON.stringify(Object.assign({}, current, { description }), null, 2) + '\n';
}

module.exports = { render, renderMenu, HEADER, MENU, FIELDS };

if (require.main === module) {
  const outputs = [[HEADER, render()], [MENU, renderMenu()]];
  const check = process.argv.includes('--check');
  let stale = false;
  for (const [file, text] of outputs) {
    const name = path.relative(ROOT, file).replace(/\\/g, '/');
    if (check) {
      const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') : '';
      if (current !== text) {
        console.error(`${name} is out of date: run node tools/gen-hub-text.js`);
        stale = true;
      } else console.log(`${name} is up to date`);
    } else {
      fs.writeFileSync(file, text);
      console.log(`wrote ${name}`);
    }
  }
  if (stale) process.exit(1);
}
